#!/bin/sh
# Rebuild static/songsterr-alphatab.js from a checkout of Songsterr Downloader (bun install done there):
#   tools/songsterr/build.sh /path/to/songsterr-downloader
set -e
SRC="$(cd "$1" && pwd)"; HERE="$(cd "$(dirname "$0")" && pwd)"; OUT="$HERE/../../static/songsterr-alphatab.js"
TMP="$SRC/.pick-build"; rm -rf "$TMP"; mkdir -p "$TMP"
cp "$HERE/entry.ts" "$HERE/alphatab-global.cjs" "$TMP/"
cat > "$TMP/tsconfig.json" <<JSON
{"compilerOptions":{"baseUrl":"..","paths":{"\$lib/*":["src/lib/*"],"@coderline/alphatab":[".pick-build/alphatab-global.cjs"]}}}
JSON
( cd "$TMP" && bun build entry.ts --format=iife --target=browser --minify --tsconfig-override=tsconfig.json --outfile=bundle.js )
{ printf '/* Songsterr -> alphaTab for Pick. Converter from Songsterr Downloader (commit %s),\n * MIT License, Copyright 2026 Ryan Roberts. Generated by tools/songsterr/build.sh - do not edit. */\n' "$(git -C "$SRC" rev-parse --short HEAD)"
  cat "$TMP/bundle.js"; } > "$OUT"
rm -rf "$TMP"; echo "$OUT $(wc -c < "$OUT") B"
